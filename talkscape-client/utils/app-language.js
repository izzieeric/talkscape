const SUPPORTED_NATIVE_LANGUAGES = ['zh-CN'];
const SUPPORTED_LEARNING_LANGUAGES = ['en'];
const SUPPORTED_LEARNING_DIFFICULTIES = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

function interpolate(template, params = {}) {
  return String(template || '').replace(/\{(\w+)\}/g, (_match, key) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : ''
  ));
}

export function normalizeNativeLanguage(value, fallback = 'zh-CN') {
  const raw = String(value || '').trim().toLowerCase();
  if (!raw) return fallback;
  if (raw === 'zh' || raw === 'zh-cn' || raw === 'zh_hans') return 'zh-CN';
  if (raw === 'en' || raw === 'en-us' || raw === 'en-gb') return 'en';
  const normalized = String(value || '').trim();
  return SUPPORTED_NATIVE_LANGUAGES.includes(normalized) ? normalized : fallback;
}

export function normalizeLearningLanguage(value, fallback = 'en') {
  const raw = String(value || '').trim().toLowerCase();
  if (!raw) return fallback;
  if (raw === 'en' || raw === 'en-us' || raw === 'en-gb') return 'en';
  return fallback;
}

export function getSoftwareLanguage(nativeLanguage = 'zh-CN') {
  return normalizeNativeLanguage(nativeLanguage, 'zh-CN');
}

export function getAppText(nativeLanguage = 'zh-CN', key, params = {}) {
  const softwareLanguage = getSoftwareLanguage(nativeLanguage);
  const text = TEXTS[softwareLanguage]?.[key] ?? TEXTS['zh-CN'][key] ?? key;
  return interpolate(text, params);
}

export function getLearningLanguageLabel(code, nativeLanguage = 'zh-CN') {
  const normalized = normalizeLearningLanguage(code, 'en');
  if (normalized === 'en') {
    return getAppText(nativeLanguage, 'lang.english');
  }
  return normalized;
}

export function getNativeLanguageLabel(code, nativeLanguage = 'zh-CN') {
  const normalized = normalizeNativeLanguage(code, 'zh-CN');
  if (normalized === 'en') return getAppText(nativeLanguage, 'lang.english');
  if (normalized === 'zh-CN') return getAppText(nativeLanguage, 'lang.chinese');
  return normalized;
}

export function getLearningLanguageOptions(nativeLanguage = 'zh-CN') {
  return SUPPORTED_LEARNING_LANGUAGES.map((value) => ({
    value,
    label: getLearningLanguageLabel(value, nativeLanguage)
  }));
}

export function getNativeLanguageOptions(nativeLanguage = 'zh-CN') {
  return SUPPORTED_NATIVE_LANGUAGES.map((value) => ({
    value,
    label: getNativeLanguageLabel(value, nativeLanguage)
  }));
}

export function getConversationStyleOptions(nativeLanguage = 'zh-CN') {
  return [
    { label: getAppText(nativeLanguage, 'style.normal'), value: 'normal' },
    { label: getAppText(nativeLanguage, 'style.professional'), value: 'professional' },
    { label: getAppText(nativeLanguage, 'style.casual'), value: 'casual' },
    { label: getAppText(nativeLanguage, 'style.internet'), value: 'internet' }
  ];
}

export function normalizeLearningDifficulty(value, fallback = 'A1') {
  const normalized = String(value || '').trim().toUpperCase();
  return SUPPORTED_LEARNING_DIFFICULTIES.includes(normalized) ? normalized : fallback;
}

export function getLearningDifficultyLabel(code, nativeLanguage = 'zh-CN') {
  const normalized = normalizeLearningDifficulty(code, 'A1');
  return getAppText(nativeLanguage, `difficulty.cefr.${normalized}`) || normalized;
}

export function getLearningDifficultyOptions(nativeLanguage = 'zh-CN') {
  return SUPPORTED_LEARNING_DIFFICULTIES.map((value) => ({
    value,
    label: getLearningDifficultyLabel(value, nativeLanguage)
  }));
}

export function normalizeSettingsPayload(settings = {}) {
  const {
    aiProvider,
    aiModel,
    ttsProvider,
    ...rest
  } = settings || {};

  return {
    ...rest,
    learningLanguage: normalizeLearningLanguage(settings.learningLanguage, 'en'),
    learningDifficulty: normalizeLearningDifficulty(settings.learningDifficulty, 'A1'),
    nativeLanguage: normalizeNativeLanguage(settings.nativeLanguage, 'zh-CN')
  };
}
